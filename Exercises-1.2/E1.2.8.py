a = 3.14159
import stdio

stdio.writeln(a) # This one just prints the value of a
stdio.writeln(a + 1.0) # This one adds 1 to the value
stdio.writeln(8 // int(a)) # This line rounds a up and divides 8 by the new a-value
stdio.writeln(8.0 / a) # This line divides 8 by the original value of a
stdio.writeln(int(8.0 / a)) # This line rounds the quotient down.

